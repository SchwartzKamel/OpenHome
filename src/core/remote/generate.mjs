import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

// Generated artifacts are checked in: a deployed browser never reads the parent repository.
const files = ['types.schema.json', 'events.schema.json', 'openapi.json']
const sources = await Promise.all(
  files.map((name) => readFile(new URL(`../../../../contracts/${name}`, import.meta.url), 'utf8'))
)
const [types, events, api] = sources.map((source) => JSON.parse(source))
const digest = createHash('sha256').update(sources.join('\n')).digest('hex')
const banner = `// Generated by generate.mjs from the frozen household v1 contract.\n// Source SHA-256: ${digest}. Do not edit by hand.\n\n`
const supported = new Set([
  '$ref',
  'type',
  'const',
  'enum',
  'oneOf',
  'allOf',
  'required',
  'properties',
  'additionalProperties',
  'items',
  'minItems',
  'maxItems',
  'uniqueItems',
  'minimum',
  'maximum',
  'minLength',
  'maxLength',
  'pattern',
  'format',
  'contentEncoding',
  'maxProperties',
])

function reference(ref, event = false) {
  const key = ref.split('/').at(-1)
  return event && !ref.startsWith('types.schema.json') ? `Event${key}` : key
}

function clean(schema, event = false) {
  const result = {}
  for (const [key, value] of Object.entries(schema)) {
    if (!supported.has(key)) continue
    if (key === '$ref') result[key] = reference(value, event)
    else if (key === 'properties') {
      result[key] = Object.fromEntries(
        Object.entries(value).map(([name, child]) => [name, clean(child, event)])
      )
    } else if (key === 'items') result[key] = clean(value, event)
    else if (key === 'oneOf' || key === 'allOf') {
      result[key] = value.map((child) => clean(child, event))
    } else result[key] = value
  }
  return result
}

function ts(schema, event = false) {
  if (schema.$ref) return reference(schema.$ref, event)
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (schema.oneOf) return schema.oneOf.map((part) => `(${ts(part, event)})`).join(' | ')
  if (schema.allOf) return schema.allOf.map((part) => `(${ts(part, event)})`).join(' & ')
  if (schema.type === 'array') return `Array<${ts(schema.items, event)}>`
  if (schema.type === 'object' || schema.properties || schema.required) {
    const required = new Set(schema.required ?? [])
    const members = Object.entries(schema.properties ?? {}).map(
      ([name, child]) =>
        `${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${ts(child, event)}`
    )
    for (const name of required) {
      if (!schema.properties?.[name]) members.push(`${JSON.stringify(name)}: unknown`)
    }
    return members.length ? `{ ${members.join('; ')} }` : 'Record<string, never>'
  }
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (['string', 'boolean', 'null'].includes(schema.type)) return schema.type
  throw new Error(`Unsupported type schema: ${JSON.stringify(schema)}`)
}

const definitions = Object.fromEntries(
  Object.entries(types.$defs).map(([name, schema]) => [name, clean(schema)])
)
let declarations = Object.entries(types.$defs)
  .map(([name, schema]) => {
    const type =
      name === 'VaultETag'
        ? '`"vault-${number}"`'
        : name === 'TradeETag'
          ? '`"trade-${number}"`'
          : ts(schema)
    return `export type ${name} = ${type}\n`
  })
  .join('\n')
for (const [name, schema] of Object.entries(events.$defs)) {
  definitions[`Event${name}`] = clean(schema, true)
  declarations += `\nexport type Event${name} = ${ts(schema, true)}\n`
}
declarations += `\nexport interface WireTypes {\n${Object.keys(definitions)
  .map((name) => `  ${name}: ${name}`)
  .join('\n')}\n}\n`

function resolve(value) {
  return value?.$ref?.startsWith('#/components/')
    ? value.$ref
        .split('/')
        .slice(1)
        .reduce((parent, key) => parent[key], api)
    : value
}

const descriptors = {}
const operationTypes = []
for (const [path, methods] of Object.entries(api.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'post', 'delete'].includes(method) || operation.operationId === 'connectEvents') {
      continue
    }
    const contract = operation['x-contract']
    const parameters = [...(methods.parameters ?? []), ...(operation.parameters ?? [])].map(resolve)
    const pathParams = parameters.filter((parameter) => parameter.in === 'path')
    const queryParams = parameters.filter((parameter) => parameter.in === 'query')
    const objectSchema = (params) => ({
      type: 'object',
      additionalProperties: false,
      properties: Object.fromEntries(params.map((p) => [p.name, p.schema])),
      required: params.filter((p) => p.required).map((p) => p.name),
    })
    const body = resolve(operation.requestBody)?.content?.['application/json']?.schema
    const [status, response] = Object.entries(operation.responses).find(([key]) =>
      key.startsWith('2')
    )
    const output = response.content?.['application/json']?.schema
    const auth = operation.security?.some((entry) => entry.SetupToken)
      ? 'setup'
      : operation.security?.length === 0
        ? 'none'
        : 'bearer'
    const ifMatch = contract.durable && contract.revision !== 'none'
    const descriptor = {
      method: method.toUpperCase(),
      path,
      auth,
      durable: contract.durable,
      revision: contract.revision,
      bodyMaxBytes: contract.body_max_bytes,
      status: Number(status),
      pathSchema: clean(objectSchema(pathParams)),
      querySchema: clean(objectSchema(queryParams)),
      ...(body && { bodySchema: clean(body) }),
      ...(output && { outputSchema: clean(output) }),
      ...(response.headers?.ETag && {
        etag: contract.revision === 'none' ? 'trade' : contract.revision,
      }),
    }
    descriptors[operation.operationId] = descriptor
    const input = []
    if (pathParams.length) input.push(`path: ${ts(objectSchema(pathParams))}`)
    if (queryParams.length) input.push(`query?: ${ts(objectSchema(queryParams))}`)
    if (body) input.push(`body: ${ts(body)}`)
    if (ifMatch) input.push(`ifMatch: ${contract.revision === 'vault' ? 'VaultETag' : 'TradeETag'}`)
    if (contract.durable) input.push('idempotencyKey?: Id')
    if (auth === 'setup') input.push('setupToken: string')
    operationTypes.push(
      `  ${operation.operationId}: { input: { ${input.join('; ')} }; output: ${output ? ts(output) : 'null'} }`
    )
  }
}
declarations += `\nexport interface ApiOperations {\n${operationTypes.join('\n')}\n}\n`
await Promise.all([
  writeFile(new URL('./wire-types.ts', import.meta.url), banner + declarations),
  writeFile(
    new URL('./wire-schema.json', import.meta.url),
    JSON.stringify({ source_sha256: digest, definitions, operations: descriptors }, null, 2) + '\n'
  ),
])
